def render(ground, path, bridge, spires, data):
    rng = np.random.default_rng(17)
    img = np.zeros((H * T, W * T, 3), dtype=np.uint8)
    canopy = np.zeros((H * T, W * T, 4), dtype=np.uint8)
    # Void: deep night with a soft nebula and stars.
    yy, xx = np.mgrid[0:H * T, 0:W * T]
    neb = (np.sin(xx / 97.0) + np.sin(yy / 71.0 + xx / 143.0) + np.sin((xx + yy) / 59.0)) / 3
    img[..., 0] = np.clip(14 + neb * 14, 0, 255)
    img[..., 1] = np.clip(12 + neb * 6, 0, 255)
    img[..., 2] = np.clip(38 + neb * 22, 0, 255)
    for _ in range(900):
        x, y = rng.integers(0, W * T), rng.integers(0, H * T)
        img[y, x] = (200, 210, 255) if rng.random() < 0.8 else (255, 220, 160)
    for _ in range(60):
        x, y = rng.integers(1, W * T - 1), rng.integers(1, H * T - 1)
        img[y, x - 1:x + 2] = (150, 160, 230)
        img[y - 1:y + 2, x] = (150, 160, 230)
    grass = {tuple(e["rect"]) for e in data["encounters"]}

    def in_grass(x, y):
        return any(x0 <= x < x0 + w and y0 <= y < y0 + h for x0, y0, w, h in grass)

    for y in range(H):
        for x in range(W):
            X, Y = x * T, y * T
            if ground[y, x]:
                # Floating island underside (drawn into the void below the island's edge).
                if y + 1 < H and not ground[y + 1, x]:
                    for d in range(1, 13):
                        if Y + T + d >= H * T:
                            break
                        shade = max(0, 70 - d * 5)
                        img[Y + T + d - 1, X:X + T] = (40 + shade // 2, 32 + shade // 3, 90 + shade)
                    img[Y + T:Y + T + 2, X:X + T] = (150, 130, 220)
                base = (84, 70, 138) if (x + y) % 2 else (90, 76, 146)
                img[Y:Y + T, X:X + T] = base
                img[Y + (x * 3 + y) % 9 + 3, X + 2:X + 8] = (120, 104, 186)  # facet glints
                img[Y + 2:Y + 7, X + (x + y * 5) % 11 + 2] = (68, 56, 118)
                if not ground[y - 1, x] if y else True:
                    img[Y:Y + 2, X:X + T] = (170, 150, 240)
                for nx, side in ((x - 1, 0), (x + 1, T - 2)):
                    if 0 <= nx < W and not ground[y, nx] and not bridge[y, nx]:
                        img[Y:Y + T, X + side:X + side + 2] = (130, 112, 200)
            if path[y, x]:
                img[Y:Y + T, X:X + T] = (196, 192, 220)
                img[Y + T - 1, X:X + T] = (150, 146, 180)
                img[Y:Y + T, X + T - 1] = (150, 146, 180)
                img[Y + 3, X + 3:X + 6] = (226, 222, 245)
            if bridge[y, x]:
                img[Y:Y + T, X:X + T] = (60, 120, 170)
                vertical = x in BRIDGE_COLS and y not in BRIDGE_ROWS
                for i in range(1, T, 4):
                    if vertical:
                        img[Y + i:Y + i + 3, X:X + T] = (110, 210, 235)
                    else:
                        img[Y:Y + T, X + i:X + i + 3] = (110, 210, 235)
                # glowing rails on the outer edges
                if vertical:
                    if x == BRIDGE_COLS[0]:
                        img[Y:Y + T, X:X + 2] = (200, 250, 255)
                    if x == BRIDGE_COLS[1]:
                        img[Y:Y + T, X + T - 2:X + T] = (200, 250, 255)
                else:
                    if y == BRIDGE_ROWS[0]:
                        img[Y:Y + 2, X:X + T] = (200, 250, 255)
                    if y == BRIDGE_ROWS[1]:
                        img[Y + T - 2:Y + T, X:X + T] = (200, 250, 255)
            if ground[y, x] and in_grass(x, y):
                img[Y:Y + T, X:X + T] = (64, 48, 116)
                for i in range(4):
                    bx = X + 1 + i * 4
                    top = Y + 3 + (i % 2) * 3
                    img[top:Y + T - 1, bx:bx + 2] = (130, 100, 230)
                    img[top:top + 2, bx:bx + 2] = (220, 200, 255)
    # Crystal spires: bases on the ground layer, tips in the canopy so you can walk behind them.
    for y in range(H):
        for x in range(W):
            if not spires[y, x]:
                continue
            X, Y = x * T, y * T
            color = [(110, 230, 240), (240, 140, 220), (180, 150, 255)][(x + y) % 3]
            dark = tuple(c // 2 for c in color)
            light = tuple(min(255, c + 50) for c in color)
            for row in range(28):
                half = max(1, (row * 6) // 28)
                yy0 = Y + T - 28 + row
                if yy0 < 0:
                    continue
                for col in range(-half, half + 1):
                    px = X + 8 + col
                    shade = light if col < 0 else (color if col == 0 else dark)
                    edge = col in (-half, half)
                    value = (30, 24, 60) if edge else shade
                    img[yy0, px] = value
                    if yy0 < Y:  # the part sticking up into the tile above goes in the canopy
                        canopy[yy0, px, :3] = value
                        canopy[yy0, px, 3] = 255
    Image.fromarray(img).save(ROOT / "assets/backgrounds/crystal_realm_tiles.png", optimize=True)
    Image.fromarray(canopy, "RGBA").save(ROOT / "assets/backgrounds/crystal_realm_canopy.png", optimize=True)


def main():
    ground, path, bridge, spires = build_layout()
    data = map_data(ground, path, bridge, spires)
    (ROOT / "data/maps/crystal_realm.json").write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n",
                                                       encoding="utf-8")
    render(ground, path, bridge, spires, data)
    print(f"crystal realm: {int(ground.sum())} island tiles, {int(bridge.sum())} bridge tiles, "
          f"{int(spires.sum())} spires")


if __name__ == "__main__":
    main()
