"""GDD 25: optional audio. Music and effects load from assets/sounds when present; missing files
fall back to tiny generated chiptune blips (or silence). Nothing here can crash the game: every
call is wrapped, and a machine without an audio device simply plays nothing."""
from array import array

from config import ROOT, WEB

WEB_BUFFER = 4096          # samples; the desktop keeps pygame's low-latency default

SOUND_DIR = ROOT / "assets" / "sounds"
# name -> (frequencies in Hz, milliseconds per note) for the generated placeholder effects.
BLIPS = {
    "select": ((880,), 40), "attack": ((330, 220), 60), "hit": ((160, 110), 70), "correct": ((660, 880), 70),
    "wrong": ((220, 180), 90), "capture": ((523, 659, 784, 1047), 80), "levelup": ((523, 659, 784), 90),
    "evolve": ((392, 523, 659, 784, 1047), 110), "heal": ((784, 988), 80),
}
# Music per state/world -> file name in assets/sounds (generated by tools/generate_audio.py).
MUSIC = {"menu": "menu", "overworld": "forest", "number_forest": "forest", "village_shop": "forest",
         "village_sanctuary": "forest", "village_recovery": "forest", "algebra_cavern": "cavern",
         "geometry_kingdom": "kingdom", "chronos_dimension": "chronos", "crystal_realm": "chronos",
         "battle": "battle", "boss": "boss",
         "wild_battle": "wild_battle", "arena": "arena"}   # recorded tracks (assets/sounds/New Sound)

_state = {"ready": None, "sounds": {}, "music": None, "enabled": True, "loop_sound": None}


def _ready():
    if _state["ready"] is None:
        try:
            import pygame
            if not pygame.mixer.get_init():
                pygame.mixer.init(44100 if WEB else 22050, -16, 2 if WEB else 1, WEB_BUFFER if WEB else 512)
            _state["ready"] = bool(pygame.mixer.get_init())
            if _state["ready"] and WEB:
                pygame.mixer.set_reserved(1)       # channel 0 is kept for the music loop
        except Exception:
            _state["ready"] = False
    return _state["ready"]


def _square(frequencies, ms, rate=22050, volume=0.18):
    samples = array("h")
    for frequency in frequencies:
        count = int(rate * ms / 1000)
        period = max(2, int(rate / frequency))
        for i in range(count):
            fade = 1 - i / count
            samples.append(int(32767 * volume * fade * (1 if (i % period) < period // 2 else -1)))
    return samples.tobytes()


def _sound(name):
    if name in _state["sounds"]:
        return _state["sounds"][name]
    import pygame
    sound = None
    for extension in (".ogg", ".wav"):
        path = SOUND_DIR / f"{name}{extension}"
        if path.exists():
            sound = pygame.mixer.Sound(str(path))
            break
    if sound is None and name in BLIPS:
        sound = pygame.mixer.Sound(buffer=_square(*BLIPS[name]))
    _state["sounds"][name] = sound
    return sound


def play(name):
    """Play a short effect by name ("attack", "capture", ...). Silently does nothing if unavailable."""
    if not _state["enabled"] or not _ready():
        return
    try:
        sound = _sound(name)
        if sound is not None:
            sound.play()
    except Exception:
        _state["sounds"][name] = None


def music(track):
    """Loop assets/sounds/<track>.ogg if it exists; otherwise keep quiet (placeholder silence)."""
    if track == _state["music"] or not _state["enabled"] or not _ready():
        return
    _state["music"] = track
    try:
        import pygame
        name = MUSIC.get(track, track)
        path = next((SOUND_DIR / f"{name}{ext}" for ext in (".ogg", ".wav") if (SOUND_DIR / f"{name}{ext}").exists()),
                    None)
        if WEB:
            _web_music(path)
        elif path is not None:
            pygame.mixer.music.load(str(path))
            pygame.mixer.music.set_volume(0.45)
            pygame.mixer.music.play(-1)
        else:
            pygame.mixer.music.stop()
    except Exception:
        pass


def _web_music(path):
    """Browser: decode the whole track once and loop it from memory. Streaming (mixer.music)
    decodes OGG chunk by chunk on the game's only thread, which crackles whenever a frame is slow."""
    import pygame
    channel = pygame.mixer.Channel(0)
    channel.stop()
    _state["loop_sound"] = None               # free the previous track
    if path is None:
        return
    sound = pygame.mixer.Sound(str(path))
    sound.set_volume(0.45)
    _state["loop_sound"] = sound
    channel.play(sound, loops=-1)


def set_enabled(enabled):
    _state["enabled"] = bool(enabled)
    if not enabled:
        try:
            import pygame
            if pygame.mixer.get_init():
                pygame.mixer.stop()
                pygame.mixer.music.stop()
                _state["loop_sound"] = None
        except Exception:
            pass

